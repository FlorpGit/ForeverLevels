-- Turn a ForeverLevels recorder log into a route skeleton.
--
-- 1. In game: /fl record on, play, then /reload or log out.
-- 2. Find WTF/Account/<ACCOUNT>/SavedVariables/Pathwise.lua
-- 3. lua tools/recorder_to_route.lua path/to/Pathwise.lua > MyRoute.lua
--
-- Each accept/turn-in becomes one step with recorded coordinates. Consecutive
-- events at the same spot (within 2 map units) are merged into one step.
-- Edit titles and text by hand afterwards; the output is only a starting point.

local path = arg[1]
if not path then
	io.stderr:write("usage: lua tools/recorder_to_route.lua <SavedVariables/Pathwise.lua> [route-id]\n")
	os.exit(2)
end
local routeId = arg[2] or "my.route"

-- SavedVariables files are plain Lua assignments; run them in an empty sandbox.
local env = {}
local chunk = assert(loadfile(path, "t", env))
if setfenv then setfenv(chunk, env) end
chunk()

local log = env.ForeverLevelsDB and env.ForeverLevelsDB.recorder
if not log or #log == 0 then
	io.stderr:write("no recorder entries found in " .. path .. "\n")
	os.exit(1)
end

local function Quote(text)
	return string.format("%q", tostring(text or ""))
end

local steps, names = {}, {}
local zones = {}
for _, entry in ipairs(log) do
	names[entry.questID] = entry.title
	if entry.zone then zones[entry.zone] = (zones[entry.zone] or 0) + 1 end
	local last = steps[#steps]
	local samePlace = last and entry.x and last.x and entry.zone == last.zone
		and math.abs(entry.x - last.x) < 2 and math.abs(entry.y - last.y) < 2
	if not samePlace then
		last = { x = entry.x, y = entry.y, zone = entry.zone, mapID = entry.mapID, accept = {}, turnin = {}, level = entry.level }
		steps[#steps + 1] = last
	end
	local list = entry.kind == "accept" and last.accept or last.turnin
	list[#list + 1] = entry.questID
end

local mainZone, best = nil, 0
for zone, count in pairs(zones) do
	if count > best then mainZone, best = zone, count end
end

local out = {}
local function W(line) out[#out + 1] = line end

W("-- Generated by tools/recorder_to_route.lua. Review every step before sharing.")
W("local ForeverLevels = _G.ForeverLevels")
W("if not ForeverLevels then return end")
W("")
W("ForeverLevels:RegisterRoute({")
W("\tid = " .. Quote(routeId) .. ",")
W("\ttitle = \"TODO title\",")
W("\tauthor = \"TODO author\",")
W("\tlicense = \"CC BY-SA 4.0\",")
W(string.format("\tlevels = { %d, %d },", log[1].level or 1, log[#log].level or 60))
if mainZone then W("\tzone = " .. Quote(mainZone) .. ",") end
W("\tquests = {")
local ids = {}
for id in pairs(names) do ids[#ids + 1] = id end
table.sort(ids)
for _, id in ipairs(ids) do
	W(string.format("\t\t[%d] = %s,", id, Quote(names[id])))
end
W("\t},")
W("\tsteps = {")
for index, step in ipairs(steps) do
	W("\t\t{")
	W(string.format("\t\t\tid = \"step-%03d\",", index))
	W("\t\t\ttitle = " .. Quote(names[step.accept[1] or step.turnin[1]]) .. ",")
	W("\t\t\ttext = \"TODO\",")
	if step.zone and step.zone ~= mainZone then W("\t\t\tzone = " .. Quote(step.zone) .. ",") end
	if step.x then W(string.format("\t\t\tx = %.1f, y = %.1f,", step.x, step.y)) end
	if #step.turnin > 0 then W("\t\t\tturnin = { " .. table.concat(step.turnin, ", ") .. " },") end
	if #step.accept > 0 then W("\t\t\taccept = { " .. table.concat(step.accept, ", ") .. " },") end
	W("\t\t},")
end
W("\t},")
W("})")

print(table.concat(out, "\n"))
