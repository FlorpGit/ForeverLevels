-- Turns a Pathwise recorder log into a route to edit.
--
-- 1. In game: /pw record on, play, then /reload or log out.
-- 2. Find WTF/Account/<ACCOUNT>/SavedVariables/Pathwise.lua
-- 3. lua tools/recorder_to_route.lua path/to/Pathwise.lua [route-id] > MyRoute.lua
--
-- Each quest accepted or handed in becomes a goal with the recorded place
-- (`at`) and NPC (`who`). Events within 2 map units of each other on the
-- same map, one after another, share a step. Titles and notes are left for
-- you to write: the output is a starting point. The format is the one in
-- docs/ROUTE_FORMAT.md; quest names and objectives come from Pathwise's data.

local path = arg[1]
if not path then
	io.stderr:write("usage: lua tools/recorder_to_route.lua <SavedVariables/Pathwise.lua> [route-id]\n")
	os.exit(2)
end
local routeId = arg[2] or "my/route"

-- A SavedVariables file is plain assignments: run it with nothing else in reach.
local env = {}
local chunk = assert(loadfile(path, "t", env))
if setfenv then setfenv(chunk, env) end
chunk()

local settings = env.PathwiseSettings
local log = settings and settings.recorder and settings.recorder.log
if type(log) ~= "table" then log = {} end
local quests = {}
for _, e in ipairs(log) do if e.kind == "accept" or e.kind == "turnin" then quests[#quests + 1] = e end end
if #quests == 0 then
	io.stderr:write("no recorded quests in " .. path .. " (turn the recorder on with /pw record on)\n")
	os.exit(1)
end

local function q(text) return ("%q"):format(tostring(text or "")) end

local steps, maps = {}, {}
for _, e in ipairs(quests) do
	if e.map then maps[e.map] = (maps[e.map] or 0) + 1 end
	local last = steps[#steps]
	local same = last and e.map and last.map == e.map and e.x and last.x
		and math.abs(e.x - last.x) < 2 and math.abs(e.y - last.y) < 2
	if not same then
		last = { map = e.map, x = e.x, y = e.y, npc = e.npc, goals = {} }
		steps[#steps + 1] = last
	end
	last.goals[#last.goals + 1] = e
end

local mainMap, best = nil, 0
for map, n in pairs(maps) do if n > best then mainMap, best = map, n end end

local out = {}
local function w(line) out[#out + 1] = line end
w("-- Generated by tools/recorder_to_route.lua from a recorder log. Check every step before sharing it.")
w("Pathwise.RegisterRoute({")
w("\tid = " .. q(routeId) .. ", title = \"TODO title\", category = \"Leveling\",")
w(("\tlevels = { %d, %d },%s"):format(quests[1].level or 1, quests[#quests].level or 60,
	mainMap and (" map = " .. mainMap .. ",") or ""))
w("\tsteps = {")
for _, step in ipairs(steps) do
	local goals = {}
	for _, e in ipairs(step.goals) do
		local g = ("{ %q, %d"):format(e.kind, e.quest)
		if e.map and e.x then g = g .. (", at = { %d, %.1f, %.1f }"):format(e.map, e.x, e.y) end
		if e.npc then g = g .. ", who = " .. q(e.npc) end
		goals[#goals + 1] = g .. " }"
	end
	w(("\t\t{ title = %s, %s },  -- %s"):format(q(step.npc or step.goals[1].title), table.concat(goals, ", "), step.goals[1].title or ""))
end
w("\t},")
w("})")

local trainers = {}
for _, e in ipairs(log) do
	if e.kind == "trainer" and e.map then trainers[#trainers + 1] = ("--   %s: map %d %.1f, %.1f (%s)"):format(e.npc, e.map, e.x, e.y, tostring(e.zone)) end
end
if #trainers > 0 then
	w("")
	w("-- Trainers recorded:")
	for _, t in ipairs(trainers) do w(t) end
end

print(table.concat(out, "\n"))
